#!/usr/bin/env bash
# Publishes the rendered PNG to a branch of the checked-out repository without touching its working tree.
# A non-default branch gets a single orphan commit, replaced on each run; the default branch gets a normal
# commit, only when the image changed. Pushing relies on the credentials configured by actions/checkout.
set -euo pipefail

image=${GC_IMAGE:-}
branch=${GC_BRANCH:-constellation}
target=${GC_PATH:-constellation.png}
message=${GC_COMMIT_MESSAGE:-Update Git Constellation image}
repo=${GC_REPO:-${GITHUB_WORKSPACE:-.}}

fail() {
    echo "Error: $*" >&2
    exit 1
}

[[ -n $image && -s $image ]] || fail "Rendered image not found: ${image:-(not set)}."
git -C "$repo" rev-parse --git-dir >/dev/null 2>&1 \
    || fail "$repo is not a Git repository. Add an actions/checkout step before this action."
git check-ref-format --branch "$branch" >/dev/null 2>&1 || fail "Invalid branch name: $branch"
case "/$target/" in
    //* | */../* | */./* | *//* | */.git/*) fail "path must be a relative file path inside the repository: $target" ;;
esac
[[ $target == *.png && $target != README.md ]] || fail "path must end in .png: $target"
[[ -n ${message//[[:space:]]/} ]] || fail "commit-message must not be empty."

export GIT_AUTHOR_NAME='github-actions[bot]'
export GIT_AUTHOR_EMAIL='41898099+github-actions[bot]@users.noreply.github.com'
export GIT_COMMITTER_NAME=$GIT_AUTHOR_NAME
export GIT_COMMITTER_EMAIL=$GIT_AUTHOR_EMAIL

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
export GIT_INDEX_FILE=$work/index

gitr() {
    git -C "$repo" "$@"
}

remote_ref=refs/heads/$branch
default_branch=$(gitr ls-remote --symref origin HEAD | sed -n 's|^ref: refs/heads/\(.*\)[[:space:]]HEAD$|\1|p')
[[ -n $default_branch ]] || fail "Could not determine the default branch of origin."

current=
if [[ -n $(gitr ls-remote origin "$remote_ref") ]]; then
    gitr fetch --quiet --no-tags --depth=1 origin "+$remote_ref:refs/git-constellation/current"
    current=$(gitr rev-parse refs/git-constellation/current)
fi

blob=$(gitr hash-object -w -- "$image")

if [[ $branch == "$default_branch" ]]; then
    [[ -n $current ]] || fail "Branch $branch does not exist on origin."
    if [[ $(gitr rev-parse -q --verify "$current:$target" || true) == "$blob" ]]; then
        echo "Image unchanged on $branch; nothing to publish."
        exit 0
    fi
    gitr read-tree "$current"
    gitr update-index --add --cacheinfo "100644,$blob,$target"
    commit=$(gitr commit-tree "$(gitr write-tree)" -p "$current" -m "$message")
    gitr push --quiet origin "$commit:$remote_ref"
else
    readme=$(printf '%s\n' \
        '# Git Constellation image' \
        '' \
        'This branch is generated by the Git Constellation GitHub Action.' \
        'Its single commit is replaced on every run; do not commit to it.' \
        | gitr hash-object -w --stdin)
    gitr update-index --add --cacheinfo "100644,$readme,README.md"
    gitr update-index --add --cacheinfo "100644,$blob,$target"
    tree=$(gitr write-tree)
    # cat-file, not rev-list: a shallow fetch hides parents, and the branch must be a single orphan commit.
    if [[ -n $current && $(gitr rev-parse "$current^{tree}") == "$tree" ]] \
        && ! gitr cat-file commit "$current" | grep -q '^parent '; then
        echo "Image unchanged on $branch; nothing to publish."
        exit 0
    fi
    commit=$(gitr commit-tree "$tree" -m "$message")
    gitr push --quiet --force origin "$commit:$remote_ref"
fi

echo "Published $target to $branch ($commit)."
